def extract_topic_and_kind(prompt: str) -> Tuple[str, str, str]:
    """Extract domain topic, document kind (brd/prd), and a clean display title."""
    p = prompt.strip()
    p_lower = p.lower()

    kind = "prd" if ("prd" in p_lower or "product requirement" in p_lower) else "brd"

    # Remove common command prefixes
    cleaned = re.sub(
        r"^(?:/doc\s+(?:brd|prd)?|create\s+(?:a\s+)?(?:brd|prd|requirements?|document)?(?:\s+for)?|generate\s+(?:a\s+)?(?:brd|prd)?(?:\s+for)?|write\s+(?:a\s+)?(?:brd|prd)?(?:\s+for)?|build\s+(?:a\s+)?(?:brd|prd)?(?:\s+for)?)\s*",
        "",
        p,
        flags=re.IGNORECASE,
    ).strip()

    if not cleaned:
        cleaned = "Enterprise Architecture & System Operations"

    topic = cleaned.rstrip(".!? ")
    # Format Title
    prefix = "Business Requirements Document (BRD)" if kind == "brd" else "Product Requirements Document (PRD)"
    display_title = f"{prefix} - {topic.title()}"
    return topic, kind, display_title


