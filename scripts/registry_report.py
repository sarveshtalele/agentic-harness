#!/usr/bin/env python3
"""Write docs/CAPABILITY_REGISTRY.md from a real registry sync against a throwaway store (plan Phase R).

  python scripts/registry_report.py

The store is a new temporary folder, so the owner's data/ is never read or written. It holds no registered MCP servers,
so the report lists none; their tools come only from a real list_tools on a running instance.
"""
from __future__ import annotations

import os
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CAPABILITY_REGISTRY.md"


def cell(text) -> str:
    return " ".join(str(text or "—").split()).replace("|", "\\|")


def tree_lines(nodes: list[dict], depth: int = 0) -> list[str]:
    lines = []
    for node in nodes:
        relation = f"{node['relation'].replace('_', ' ')}: " if node["relation"] else ""
        lines.append(f"{'  ' * depth}- {relation}{node['kind']} `{node['qualified_name']}`")
        lines += tree_lines(node["children"], depth + 1)
    return lines


def report() -> str:
    from backend import db
    from backend.core import registry
    from backend.core.registry import read

    db.migrate()
    version = registry.sync(by="scripts/registry_report.py")
    found = read.visible_rows(None)
    links = read.visible_links(found)
    counts = Counter(c["kind"] for c in found.values())
    lines = ["# Capability registry", "",
             f"Generated by `python scripts/registry_report.py` from a real sync against a throwaway store on {version['synced_at']}. "
             "Do not edit by hand; run the script again. Every row comes from code or a manifest (see `src/backend/core/registry/`).", "",
             f"Version hash `{version['hash']}`: {version['capabilities']} capabilities, {version['links']} links.", "",
             "| Kind | Count |", "|---|---|", *[f"| {k} | {n} |" for k, n in sorted(counts.items())], ""]
    if version["problems"]:
        lines += ["## What the sync could not derive", "", *[f"- {cell(p)}" for p in version["problems"]], ""]
    if not counts.get("mcp_server"):
        lines += ["No MCP server is registered in a throwaway store, so none is listed. A running instance lists each registered server and the tools its real `list_tools` returned.", ""]
    for kind in sorted(counts):
        lines += [f"## {kind} ({counts[kind]})", "", "| Name | Description | Source | Risk | Approval | Links down |", "|---|---|---|---|---|---|"]
        for c in sorted((c for c in found.values() if c["kind"] == kind), key=lambda c: c["qualified_name"]):
            down = sorted(f"{l['relation']} {found[l['to_id']]['qualified_name']}" for l in links if l["from_id"] == c["id"])
            lines.append(f"| `{cell(c['qualified_name'])}` | {cell(c['description'])} | {cell(c['source'])} | {cell(c['risk'])} | "
                         f"{'yes' if c['needs_approval'] else 'no'} | {cell('; '.join(down))} |")
        lines.append("")
    lines += ["## Nesting", "", "Plugin → commands, skills, agents, hooks, scripts; workflow → stages → agents → tools and skills; MCP server → tools.", "",
              *tree_lines(read.tree(None)), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    os.environ["ATLAS_DATA_DIR"] = tempfile.mkdtemp(prefix="registry-report-")
    os.environ["ATLAS_WORKSPACES"] = str(Path(os.environ["ATLAS_DATA_DIR"]) / "projects")
    sys.path[:0] = [str(ROOT / "src"), str(ROOT)]
    OUT.write_text(report(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
